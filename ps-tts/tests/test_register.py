@pytest.mark.parametrize("text,requested,ok", CHECKS)
def test_check(text: str, requested: str, ok: bool) -> None:
    passed, found, reason = check(text, requested)
    assert passed is ok
    assert found == detect(text)
    assert (reason == "") is ok


def test_check_reasons() -> None:
    assert check("같이 가자.", "해요체")[2] == "말투: 해요체 요청인데 반말 문장"
    assert check("같이 가자.", "하십시오체")[2] == "말투: 하십시오체 요청인데 반말 문장"
    assert check("감사합니다. 고마워요.", "반말")[2] == "말투: 반말 요청인데 해요체·하십시오체 문장"
    assert check("고마워요.", "하십시오체")[2] == "말투: 하십시오체 요청인데 해요체 문장만 있음"


def test_check_empty_request_means_unspecified() -> None:
    assert check("같이 가자.", "") == (True, ["반말"], "")


def test_check_rejects_unknown_register() -> None:
    with pytest.raises(ValueError):
        check("같이 가자.", "존댓말")
